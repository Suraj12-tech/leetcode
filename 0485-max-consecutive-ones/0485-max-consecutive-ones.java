class Solution {
    public int findMaxConsecutiveOnes(int[] arr) {
        int count = 0;
        int ptr = 0;
        int ans = 0;
        for (int i = 0; i < arr.length; i++) {
            if (arr[i] == 1) {
                count++;
            } else {
                count = 0;
            }
            ans = Math.max(ans, count);

        }

        return ans;
    }
}

